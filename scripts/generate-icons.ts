/**
 * Turns the icon sources in `src/components/icons/source` into React Native
 * data and components: `glyphs.ts` and `index.ts` next to them.
 *
 * Sources are geometry only (see `icons.yaml`). Stroke width, caps and joins
 * come from the `dna` block, so every icon gets the same line.
 *
 * Run: bun run icons
 */
import fs from "node:fs";
import path from "node:path";
import { parse } from "yaml";

const ROOT = path.resolve(import.meta.dir, "..");
const ICONS_DIR = path.join(ROOT, "src/components/icons");
const SOURCE_DIR = path.join(ICONS_DIR, "source");

const ELEMENT_TAGS = new Set([
  "path",
  "circle",
  "ellipse",
  "rect",
  "line",
  "polyline",
  "polygon",
]);

type GlyphElement = [string, Record<string, string | number>];

interface Dna {
  stroke: number;
  caps: string;
  joins: string;
}

const camel = (name: string) =>
  name.replaceAll(/-(?<letter>[a-z0-9])/gu, (_, letter: string) =>
    letter.toUpperCase()
  );

const pascal = (name: string) => {
  const c = camel(name);
  return c.charAt(0).toUpperCase() + c.slice(1);
};

const readAttributes = (raw: string) => {
  const attributes: Record<string, string> = {};
  for (const [, key, value] of raw.matchAll(
    /(?<key>[\w:-]+)="(?<value>[^"]*)"/gu
  )) {
    attributes[key] = value;
  }
  return attributes;
};

/** Every drawing element of a source, split into outline and silhouette. */
export const parseSource = (svg: string) => {
  const strokes: GlyphElement[] = [];
  const silhouette: GlyphElement[] = [];
  for (const [, type, raw] of svg.matchAll(
    /<(?<type>\w+)\s(?<raw>[^>]*?)\/?>/gu
  )) {
    if (!ELEMENT_TAGS.has(type)) {
      continue;
    }
    const { "data-role": role, ...geometry } = readAttributes(raw);
    const attributes = Object.fromEntries(
      Object.entries(geometry).map(([key, value]) => [
        camel(key),
        /^-?\d*\.?\d+$/u.test(value) ? Number(value) : value,
      ])
    );
    (role === "silhouette" ? silhouette : strokes).push([type, attributes]);
  }
  return { strokes, silhouette };
};

const withKeys = (elements: GlyphElement[], prefix: string, extra = {}) =>
  elements.map(([type, attributes], index): GlyphElement => [
    type,
    { ...attributes, ...extra, key: `${prefix}${index}` },
  ]);

const main = () => {
  const config = parse(fs.readFileSync(path.join(ROOT, "icons.yaml"), "utf-8"));
  // SAFETY: `icons draw-icons check` validates the dna block of icons.yaml.
  const dna = config.dna as Dna;
  const stroke = {
    strokeWidth: dna.stroke,
    strokeLinecap: dna.caps,
    strokeLinejoin: dna.joins,
  };
  const names = fs
    .readdirSync(SOURCE_DIR)
    .filter((file) => file.endsWith(".svg") && !file.includes("@"))
    .map((file) => file.slice(0, -4))
    .sort();

  const glyphs = names.map((name) => {
    const svg = fs.readFileSync(path.join(SOURCE_DIR, `${name}.svg`), "utf-8");
    const { strokes, silhouette } = parseSource(svg);
    const glyph = {
      outline: withKeys(strokes, "o", stroke),
      silhouette: withKeys(silhouette, "s"),
    };
    return `export const ${camel(name)}: Glyph = ${JSON.stringify(glyph)};`;
  });

  const header =
    "// Generated by scripts/generate-icons.ts from source/*.svg. Do not edit.\n";
  fs.writeFileSync(
    path.join(ICONS_DIR, "glyphs.ts"),
    `${header}import type { Glyph } from "./glyph";\n\n${glyphs.join("\n")}\n`
  );
  fs.writeFileSync(
    path.join(ICONS_DIR, "index.ts"),
    `${header}import { createIcon } from "./create-icon";\nimport * as glyphs from "./glyphs";\n\nexport type { Glyph } from "./glyph";\nexport type { Icon, IconProps } from "./create-icon";\n\n${names
      .map(
        (name) =>
          `export const ${pascal(name)}Icon = createIcon(glyphs.${camel(name)});`
      )
      .join("\n")}\n`
  );
  console.log(`${names.length} icons`);
};

if (import.meta.main) {
  main();
}
