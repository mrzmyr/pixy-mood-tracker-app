/** Section color of an icon: the guessed tag color for it. */
export const tagColorForIcon = (icon: TagIconKey): string | undefined =>
  TAG_ICON_CATEGORIES.find((category) =>
    category.icons.some((key) => key === icon)
  )?.color;

